export function getPassagesByLanguage(lang) {
  if (!lang || lang === 'all') return PASSAGES;
  return PASSAGES.filter(p => p.language === lang);
}

export function getPassageById(id, customPassages = []) {
  const defaultFound = PASSAGES.find(p => p.id === id);
  if (defaultFound) return defaultFound;
  return customPassages.find(p => p.id === id) || null;
}
